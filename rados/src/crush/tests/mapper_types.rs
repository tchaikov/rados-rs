#[test]
fn msr_rejects_overflowing_products_and_limits_undo_to_requested_output() {
    let mut map = map();
    let rule = map.rules[0].as_mut().unwrap();
    rule.rule_type = RuleType::MsrFirstN;
    rule.steps[0].arg1 = -1;
    rule.steps[1] = CrushRuleStep {
        op: RuleOp::ChooseMsr,
        arg1: 65536,
        arg2: 1,
    };
    rule.steps.insert(
        2,
        CrushRuleStep {
            op: RuleOp::ChooseMsr,
            arg1: 65536,
            arg2: 0,
        },
    );
    let mut result = Vec::new();
    assert!(crush_do_rule(&map, 0, 0, &mut result, 1, &[0x10000; 4]).is_err());

    let rule = map.rules[0].as_mut().unwrap();
    rule.steps[0].arg1 = -2;
    rule.steps[1] = CrushRuleStep {
        op: RuleOp::ChooseMsr,
        arg1: i32::MAX,
        arg2: 0,
    };
    rule.steps.remove(2);
    crush_do_rule(&map, 0, 0, &mut result, 1, &[0x10000; 4]).unwrap();
    assert_eq!(result.len(), 1);
    assert!((0..4).contains(&result[0]));
}
